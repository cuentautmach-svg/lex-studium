import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const files = ['base.css', 'archivo.css', 'foro.css', 'orbita.css', 'simulator.css', 'progressive.css'];
const css = await Promise.all(files.map(file => readFile(new URL('design-proposals/' + file, root), 'utf8')));
await writeFile(new URL('experience.css', root), '/* Generated by scripts/build-designs.mjs. Edit design-proposals/ sources. */\n' + css.join('\n\n'));
console.log('Archivo Vivo, Foro y Órbita integrados en experience.css.');
